"""
FastAPI router for Visit Management and structured medical report ingestion from Member 2.
"""

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.schemas.visit import VisitCreate, VisitResponse, VisitUpdate
from app.services.patient_service import get_patient_by_id
from app.services.visit_service import create_visit, get_visit_by_id, update_visit_report

router = APIRouter(prefix="/visits", tags=["Visits"])


@router.post(
    "/",
    response_model=VisitResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Ingest structured medical report for a patient",
    description="Ingests a structured medical report generated by Member 2, verifies the patient exists, and records the visit."
)
def ingest_visit_report(
    visit_in: VisitCreate,
    db: Session = Depends(get_db)
) -> VisitResponse:
    """
    Ingest a new visit report.
    Returns HTTP 404 if the patient does not exist.
    """
    patient = get_patient_by_id(db=db, patient_id=visit_in.patient_id)
    if not patient:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Patient with ID '{visit_in.patient_id}' not found."
        )

    visit = create_visit(db=db, visit_in=visit_in)
    return visit


@router.get(
    "/{visit_id}",
    response_model=VisitResponse,
    status_code=status.HTTP_200_OK,
    summary="Get visit by ID",
    description="Retrieves a specific visit record by its unique visit ID (e.g. VIS-2026-0001)."
)
def get_visit(
    visit_id: str,
    db: Session = Depends(get_db)
) -> VisitResponse:
    """Retrieve visit by visit_id. Returns 404 if not found."""
    visit = get_visit_by_id(db=db, visit_id=visit_id)
    if not visit:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Visit with ID '{visit_id}' not found."
        )
    return visit


@router.patch(
    "/{visit_id}",
    response_model=VisitResponse,
    status_code=status.HTTP_200_OK,
    summary="Update structured visit report",
    description="Persists updated structured visit report fields (such as voice corrections, correction history, and confirmation status) for an existing visit."
)
def patch_visit(
    visit_id: str,
    visit_update: VisitUpdate,
    db: Session = Depends(get_db)
) -> VisitResponse:
    """Update an existing visit's structured report. Returns 404 if visit is not found."""
    visit = get_visit_by_id(db=db, visit_id=visit_id)
    if not visit:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Visit with ID '{visit_id}' not found."
        )
    return update_visit_report(db=db, visit=visit, visit_update=visit_update)
